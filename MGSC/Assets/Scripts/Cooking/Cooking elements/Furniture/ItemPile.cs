

using Controller;
using Cooking;
using System.Collections.Generic;
using Unity.VisualScripting.Antlr3.Runtime.Tree;
using UnityEditor;
using UnityEngine;
using UnityEngine.Events;

public class ItemPile : ObjectPile, IMultiContainer, ICallbackBroadcaster
{
    #region Properties


    public List<IGrabbable> HeldItems { get; set; } = new();

    public UnityEvent<IGrabbable> OnGrab { get; set; }

    public UnityEvent<IGrabbable> OnDrop { get; set; }

    public bool IsLocked { get; set; }

    public bool Passthrough => true;

    public IGrabbable HeldItem
    {
        get
        {
            if (!_replaceItemsByProxies)
                return HeldItems.Count > 0 ? HeldItems[^1] : null;

            else
                return _tempItem;
        }
    }
    
    public PlayerInterface Player { get; set; }
    public bool EnableCallbacks { get; set; }

    public ICallbackBroadcaster Self => this;
    #endregion

    #region Fields

    [Space(20f)]
    [Header("Item parameters")]
    [SerializeField] private Item _itemPrefab;
    [SerializeField] private bool _replaceItemsByProxies;

    // Private fields
    private ItemManager _itemManager;
    private CapsuleCollider _capsuleCollider;
    private IGrabbable _tempItem;

    #endregion


    #region Methods

    private void Start()
    {
        Reference.GetManager(out _itemManager);
        Setup();
    }

    public void Setup()
    {
        _capsuleCollider = GetComponent<CapsuleCollider>();
        TryRegenerate();
        UpdateCollider();

        HeldItems.Clear();

        foreach (var go in Objects)
        {
            RequestGrab(go.GetComponent<Item>());
        }

        if (_itemPrefab == null)
            Debug.LogWarning("The item prefab reference is null on '" + name + "', please reference it in the inspector");

        NewTempItem();
        //SetPlateComponentsEnabled(false);
    }

    private void NewTempItem(Vector3 position=default, Quaternion rotation=default)
    {
        if (_tempItem == null && _itemPrefab != null)
        {
            GameObject go = Instantiate(_itemPrefab, this.transform).gameObject;
            go.name = "New item generated by " + name;
            _tempItem = go.GetComponent<Item>();
            _tempItem.Container = this;

            if (rotation == default)
                RotateByParameters(go);
            else
                go.transform.rotation = rotation;

            if (position == default)
            {
                OffsetByParameters(go);
                PutOnTop(go);
            }
            else
                go.transform.position = position;
            //_tempItem.transform.gameObject.SetActive(false);
        }
    }

    public void Empty()
    {
        foreach (var item in GetComponentsInChildren<Item>(true))
        {
            _itemManager.Despawn(item);
        }
        HeldItems.Clear();
        TryRegenerate();
    }

    public bool RequestGrab(IGrabbable item)
    {
        return TryGrab(item);
    }

    public bool RequestDrop(IGrabbable item = null)
    {
        return TryDrop(item);
    }
    private bool TryGrab(IGrabbable item)
    {
        if (!CanGrab(item))
            return false;
        Grab(item);
        return true;
    }

    private bool TryDrop(IGrabbable item = null)
    {
        if (!CanDrop(item))
            return false;
        Drop(item);
        return true;
    }
    public bool CanGrab(IGrabbable item)
    {
        if (item == null) return false;
        if (IsLocked) return false;
        if (item.IsLocked) return false;
        if (item.Container != null && item.Container.IsLocked) return false;
        if (HeldItems.Contains(item)) return false;
        if (item is not Item) return false;
        


        return true;
    }

    public bool CanDrop(IGrabbable item = null)
    {
        if (item == null) return false;
        if (HeldItem != item) return false;
        if (IsLocked) return false;
        if (item.IsLocked) return false;
        if (!_replaceItemsByProxies && !HeldItems.Contains(item)) return false;
        if (_replaceItemsByProxies && item != _tempItem) return false;
        if (item is not Item) return false;
        if (Objects.Count <= (_replaceItemsByProxies?-1:0)) return false;

        return true;
    }
    private void Grab(IGrabbable item)
    {
        Debug.Log("GRAAAAAAB ZIBCZPRIHFBPIUEB");
        if (!_replaceItemsByProxies)
        {
            TryAdd(item.transform.gameObject);
            HeldItems.Add(item);
            item.Container = this;
            item.Collider.enabled = false;
        }
        else
        {
            if (!TryDispose(item.transform.gameObject))
                throw new System.Exception("Couldn't destroy the following object '" +
                    item.transform.name + "' when trying to replace it by a proxy on item pile '" + this.name + "'.");

            
            if (_tempItem != null)
            {
                _tempItem.transform.gameObject.SetActive(false);
                if (item.Container != this as IContainer)
                {
                    Debug.Log("Arg FUUUUUUUCK");
                    TryAdd(_tempItem.transform.localPosition, _tempItem.transform.rotation, _tempItem.transform.localScale);
                }
                else
                    TryAdd();
                PutOnTop(_tempItem.transform.gameObject);
                _tempItem.transform.gameObject.SetActive(true);
            }
            else
                TryAdd();
        }
        Self.Callback(OnGrab, item);
        UpdateCollider();
    }
    private void Drop(IGrabbable item)
    {
        if (!_replaceItemsByProxies)
        {
            Debug.Log("PlatePile drops an item");
            TryRemove(item.transform.gameObject);
            HeldItems.Remove(item);
            item.Collider.enabled = true;
        }
        else
        {
            _tempItem.transform.gameObject.SetActive(true);
            Vector3 pos = default;
            Quaternion rot = default;
            if (TryGet(Objects.Count-1, out var go))
            {
                pos = go.transform.position;
                rot = go.transform.rotation;
            }

            bool itemsLeft = TryDispose(Objects.Count-1);
            if (_tempItem.transform.parent == this.transform)
            {
                _tempItem.transform.SetParent(null);
            }
            _tempItem.transform.rotation = Quaternion.identity;
            _tempItem = null;
            if (_itemPrefab == null)
                Debug.LogError("Cannot instantiate a null object : Please reference the item prefab in the inspector. (" + name + ")");
            else if (itemsLeft)
                NewTempItem(pos, rot);
        }

        Self.Callback(OnDrop, item);
        UpdateCollider();
    }
    public void UpdateCollider()
    {
        var bounds = CalculateLocalBounds(this.gameObject);
        _capsuleCollider.radius = Mathf.Max(bounds.size.x, bounds.size.z)/2; // The radius is inscribed in the bounds, so there can be geometry outside of the collider
        _capsuleCollider.height = bounds.size.y+_capsuleCollider.radius/2;
        _capsuleCollider.center = Vector3.up * Height / 2;

        if (Mathf.Max(bounds.size.x, bounds.size.y, bounds.size.z) < 0.05f)
            _capsuleCollider.enabled = false;
        else
            _capsuleCollider.enabled = true;
    }

    public override bool TryDispose(GameObject go)
    {
        if (go == null) return false;
        if (_itemManager != null && go.TryGetComponent<Item>(out Item item))
        {
            _itemManager.Despawn(item);
            return true;
        }
        return base.TryDispose(go);
    }

    public override void OnValueChange()
    {
        base.OnValueChange();
        UpdateCollider();
    }

    protected override GameObject SelectPrefab()
    {
        if (!_replaceItemsByProxies)
            return _itemPrefab.gameObject;

        return base.SelectPrefab();
    }
    #endregion
}

#if UNITY_EDITOR

[CustomEditor(typeof(ItemPile))]
public class ItemPileEditor : Editor
{
    public override void OnInspectorGUI()
    {
        var objectPile = (ItemPile)target;
        EditorGUI.BeginChangeCheck();
        base.OnInspectorGUI();
        if (EditorGUI.EndChangeCheck())
        {
            objectPile.OnValueChange();
        }
        GUILayout.BeginHorizontal();
        if (GUILayout.Button("Regenerate"))
        {
            objectPile.DisposeAll();
            objectPile.TryRegenerate();
        }
        if (GUILayout.Button("Random seed"))
        {
            objectPile.RandomizeSeed();
            objectPile.TryRegenerate();
        }
        GUILayout.EndHorizontal();

    }
}
#endif